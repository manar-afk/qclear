'use client';

import React from 'react';
import { usePreferences } from '@/context/PreferencesContext';
import { Sparkles, Shield, HeartPulse, Leaf, Clock, DollarSign } from 'lucide-react';

interface ActionCardProps {
  title: string;
  actionText: string;
  rationale?: string;
  timeBlock?: string;
  tier?: string;
  costEstimate?: string;
  maskGuidance?: string;
  indoorReductionPct?: number;
  weeklyEmissionsAvoidedG?: number;
  isAIGenerated?: boolean;
  modelName?: string;
}

export function ActionCard({
  title,
  actionText,
  rationale,
  timeBlock,
  tier,
  costEstimate,
  maskGuidance,
  indoorReductionPct = 0,
  weeklyEmissionsAvoidedG = 0,
  isAIGenerated = false,
  modelName = 'gemini-3.5-flash',
}: ActionCardProps) {
  const { language, t } = usePreferences();

  // Tier translation badge
  const renderTierBadge = () => {
    if (!tier) return null;
    let label = 'Tier 0: Free';
    let color = 'bg-emerald-100 text-emerald-800 dark:bg-emerald-950 dark:text-emerald-300 border-emerald-300';
    if (tier === 'tier_1_budget') {
      label = 'Tier 1: Budget DIY';
      color = 'bg-blue-100 text-blue-800 dark:bg-blue-950 dark:text-blue-300 border-blue-300';
    } else if (tier === 'tier_2_purifier') {
      label = 'Tier 2: Purifier Optimization';
      color = 'bg-purple-100 text-purple-800 dark:bg-purple-950 dark:text-purple-300 border-purple-300';
    }
    return (
      <span className={`text-[10px] font-bold uppercase tracking-wider px-2 py-0.5 rounded-md border ${color}`}>
        {label}
      </span>
    );
  };

  return (
    <article className="p-4 sm:p-5 rounded-2xl bg-white dark:bg-slate-800/80 border border-slate-200/90 dark:border-slate-700 shadow-sm hover:shadow-md transition flex flex-col justify-between space-y-4">
      <div className="space-y-3">
        {/* Top Badges */}
        <div className="flex flex-wrap items-center justify-between gap-2">
          <div className="flex items-center gap-2">
            {timeBlock && (
              <span className="inline-flex items-center gap-1 text-xs font-bold px-2.5 py-1 rounded-lg bg-blue-100 text-blue-800 dark:bg-blue-950/80 dark:text-blue-300">
                <Clock className="w-3.5 h-3.5" /> {timeBlock}
              </span>
            )}
            {renderTierBadge()}
          </div>

          {/* AI vs Offline Badge */}
          <span
            className={`inline-flex items-center gap-1 text-[11px] font-semibold px-2.5 py-0.5 rounded-full border ${
              isAIGenerated
                ? 'bg-purple-50 text-purple-700 border-purple-200 dark:bg-purple-950/60 dark:text-purple-300 dark:border-purple-800'
                : 'bg-slate-100 text-slate-600 border-slate-200 dark:bg-slate-700 dark:text-slate-300 dark:border-slate-600'
            }`}
            title={isAIGenerated ? `Generated by Google Cloud Vertex AI (${modelName})` : 'Curated offline environmental health guidance'}
          >
            {isAIGenerated ? (
              <>
                <Sparkles className="w-3 h-3 text-purple-600" />
                <span>AI-Generated ({modelName})</span>
              </>
            ) : (
              <>
                <Shield className="w-3 h-3 text-slate-500" />
                <span>{t.offlineGuidanceBadge}</span>
              </>
            )}
          </span>
        </div>

        {/* Title & Core Action */}
        <div>
          <h4 className="text-base font-bold text-slate-900 dark:text-white leading-snug">
            {title}
          </h4>
          {costEstimate && (
            <div className="flex items-center gap-1 text-xs font-semibold text-emerald-600 dark:text-emerald-400 mt-0.5">
              <DollarSign className="w-3.5 h-3.5" />
              <span>{costEstimate}</span>
            </div>
          )}
          <p className="text-xs sm:text-sm text-slate-700 dark:text-slate-200 mt-2 font-medium leading-relaxed">
            {actionText}
          </p>
        </div>

        {/* Rationale or Mask Guidance */}
        {rationale && (
          <div className="text-xs text-slate-500 dark:text-slate-400 bg-slate-50 dark:bg-slate-900/40 p-2.5 rounded-xl border border-slate-100 dark:border-slate-800">
            <strong>{t.whyThisMatters}:</strong> {rationale}
          </div>
        )}

        {maskGuidance && (
          <div className="text-xs text-blue-800 dark:text-blue-300 bg-blue-50/60 dark:bg-blue-950/40 p-2.5 rounded-xl border border-blue-100 dark:border-blue-900 flex items-start gap-1.5">
            <Shield className="w-3.5 h-3.5 mt-0.5 flex-shrink-0" />
            <span>
              <strong>{language === 'hi' ? 'मास्क सलाह:' : 'Mask Guidance:'}</strong> {maskGuidance}
            </span>
          </div>
        )}
      </div>

      {/* Direct Impact Explainer Badges */}
      <div className="pt-3 border-t border-slate-100 dark:border-slate-700/60 flex flex-wrap items-center justify-between gap-2 text-xs">
        {indoorReductionPct > 0 && (
          <div className="flex items-center gap-1.5 text-emerald-700 dark:text-emerald-400 font-semibold bg-emerald-50 dark:bg-emerald-950/40 px-2.5 py-1 rounded-lg border border-emerald-200 dark:border-emerald-800/80">
            <HeartPulse className="w-3.5 h-3.5" />
            <span>~{indoorReductionPct}% {language === 'hi' ? 'इनडोर धुआं बचाव' : 'Indoor PM2.5 Reduction'} (Est.)</span>
          </div>
        )}

        {weeklyEmissionsAvoidedG > 0 && (
          <div className="flex items-center gap-1.5 text-blue-700 dark:text-blue-400 font-semibold bg-blue-50 dark:bg-blue-950/40 px-2.5 py-1 rounded-lg border border-blue-200 dark:border-blue-800/80">
            <Leaf className="w-3.5 h-3.5" />
            <span>~{weeklyEmissionsAvoidedG}g {language === 'hi' ? 'साप्ताहिक धुआं बचत' : 'Emissions Avoided/wk'} (Est.)</span>
          </div>
        )}
      </div>
    </article>
  );
}
